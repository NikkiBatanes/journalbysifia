const hashString = (value: string): number => {
  let hash = 7;
  for (let index = 0; index < value.length; index += 1) {
    hash = (hash * 31 + value.charCodeAt(index)) % 2147483647;
  }
  return hash;
};

const createRandom = (initialSeed: number) => {
  let seed = initialSeed || 1;
  return () => {
    seed = seed * 48271 % 2147483647;
    return seed / 2147483647;
  };
};

const shuffledIndexes = (length: number, seed: number): number[] => {
  const indexes = Array.from({length}, (_, index) => index);
  const random = createRandom(seed);
  for (let index = indexes.length - 1; index > 0; index -= 1) {
    const swapIndex = Math.floor(random() * (index + 1));
    [indexes[index], indexes[swapIndex]] = [indexes[swapIndex], indexes[index]];
  }
  return indexes;
};

const getCalendarDay = (date: string | Date): number => {
  if (typeof date === 'string') {
    const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(date);
    if (match) {
      return Math.floor(Date.UTC(Number(match[1]), Number(match[2]) - 1, Number(match[3])) / 86400000);
    }
  }
  const value = date instanceof Date ? date : new Date(date);
  if (Number.isNaN(value.getTime())) {return 0;}
  return Math.floor(Date.UTC(value.getFullYear(), value.getMonth(), value.getDate()) / 86400000);
};

export const getDailyClosingMessage = ({
  userId,
  date,
  flow,
}: {
  userId?: string | null;
  date: string | Date;
  flow: ClosingMessageFlow;
}): string => {
  const messages = flow === 'morning' ? MORNING_CLOSING_MESSAGES : EVENING_CLOSING_MESSAGES;
  const order = shuffledIndexes(messages.length, hashString(`${userId || 'guest'}:${flow}:v1`));
  const dayIndex = ((getCalendarDay(date) % messages.length) + messages.length) % messages.length;
  return messages[order[dayIndex]];
};

-- Journal by siFia prelaunch signups.
-- Public visitors submit through the journal-early-access Edge Function only.

create table if not exists public.journal_early_access (
  id bigint generated by default as identity primary key,
  email text not null unique,
  platform text not null check (platform in ('iphone', 'android')),
  email_consent boolean not null default false,
  consent_at timestamptz,
  consent_version text,
  founding_offer_version text,

  current_journaling text check (
    current_journaling is null or current_journaling in (
      'paper', 'notes', 'journal-app', 'mix', 'not-consistent', 'not-currently'
    )
  ),
  feature_interests jsonb,
  price_reaction text check (
    price_reaction is null or price_reaction in (
      'easy-decision', 'reasonable', 'try-first', 'too-expensive'
    )
  ),
  price_region text check (
    price_region is null or price_region in ('ph', 'international')
  ),
  survey_version text,
  tester_opt_in boolean not null default false,
  anything_else text,
  survey_completed_at timestamptz,

  source text not null default 'journal-early-access',
  utm_source text,
  utm_medium text,
  utm_campaign text,
  utm_content text,
  utm_term text,
  landing_page text,
  referrer_domain text,
  user_agent text,
  signup_token_hash text not null unique check (signup_token_hash ~ '^[a-f0-9]{64}$'),
  unsubscribed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint journal_early_access_email_normalized check (email = lower(email)),
  constraint journal_early_access_feature_interests_array check (
    feature_interests is null or jsonb_typeof(feature_interests) = 'array'
  )
);

create index if not exists journal_early_access_tester_idx
  on public.journal_early_access (tester_opt_in);
create index if not exists journal_early_access_platform_idx
  on public.journal_early_access (platform);
create index if not exists journal_early_access_created_idx
  on public.journal_early_access (created_at desc);

alter table public.journal_early_access enable row level security;

-- No anon/authenticated policies are created. Browser clients cannot read or
-- write the table. Only the server-side Edge Function may call these RPCs.
revoke all on table public.journal_early_access from anon, authenticated;

create or replace function public.journal_early_access_start(
  p_email text,
  p_platform text,
  p_source text,
  p_utm_source text,
  p_utm_medium text,
  p_utm_campaign text,
  p_utm_content text,
  p_utm_term text,
  p_landing_page text,
  p_referrer_domain text,
  p_consent_version text,
  p_founding_offer_version text,
  p_user_agent text,
  p_token_hash text
) returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.journal_early_access (
    email, platform, email_consent, consent_at, source, utm_source, utm_medium,
    utm_campaign, utm_content, utm_term, landing_page, referrer_domain,
    consent_version, founding_offer_version, user_agent, signup_token_hash
  ) values (
    p_email, p_platform, true, now(), p_source, p_utm_source, p_utm_medium,
    p_utm_campaign, p_utm_content, p_utm_term, p_landing_page, p_referrer_domain,
    p_consent_version, p_founding_offer_version, p_user_agent, p_token_hash
  )
  on conflict (email) do update set
    platform = excluded.platform,
    email_consent = true,
    consent_at = now(),
    consent_version = excluded.consent_version,
    founding_offer_version = coalesce(
      journal_early_access.founding_offer_version,
      excluded.founding_offer_version
    ),
    user_agent = excluded.user_agent,
    signup_token_hash = excluded.signup_token_hash,
    updated_at = now();
end;
$$;

create or replace function public.journal_early_access_save_survey(
  p_token_hash text,
  p_current_journaling text,
  p_feature_interests jsonb,
  p_price_region text,
  p_survey_version text,
  p_price_reaction text,
  p_tester_opt_in boolean,
  p_anything_else text
) returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.journal_early_access set
    current_journaling = p_current_journaling,
    feature_interests = p_feature_interests,
    price_region = p_price_region,
    survey_version = p_survey_version,
    price_reaction = case when p_price_region is null then null else p_price_reaction end,
    tester_opt_in = p_tester_opt_in,
    anything_else = p_anything_else,
    survey_completed_at = now(),
    updated_at = now()
  where signup_token_hash = p_token_hash;

  return found;
end;
$$;

revoke all on function public.journal_early_access_start(
  text, text, text, text, text, text, text, text, text, text, text, text, text, text
) from public, anon, authenticated;
revoke all on function public.journal_early_access_save_survey(
  text, text, jsonb, text, text, text, boolean, text
) from public, anon, authenticated;

grant execute on function public.journal_early_access_start(
  text, text, text, text, text, text, text, text, text, text, text, text, text, text
) to service_role;
grant execute on function public.journal_early_access_save_survey(
  text, text, jsonb, text, text, text, boolean, text
) to service_role;

comment on table public.journal_early_access is
  'Consent-backed Journal by siFia prelaunch signups and optional product research.';

